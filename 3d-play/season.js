const FIELDS = ['sky','fog','mid','near','limb','edge','hi','light','blossom','leaf','gold','twig','snow','rain','mist','fire','night','water'];

function hex2rgb(h){ const n=parseInt(h.slice(1),16); return [(n>>16)&255,(n>>8)&255,n&255]; }
function mixRGB(a,b,t){ return [a[0]+(b[0]-a[0])*t, a[1]+(b[1]-a[1])*t, a[2]+(b[2]-a[2])*t]; }
const KEYS = K.map(row=>{ const o={}; FIELDS.forEach((f,i)=>{ const v=row[i+1]; o[f]= typeof v==='string'? hex2rgb(v): v; }); return o; });
const smooth = t => t*t*(3-2*t);

export function climateAt(phase){
  const p = ((phase%24)+24)%24;
  const a = Math.floor(p), b=(a+1)%24, t=smooth(p-a);
  const A=KEYS[a], B=KEYS[b], out={};
  for(const f of FIELDS){ out[f] = Array.isArray(A[f]) ? mixRGB(A[f],B[f],t) : A[f]+(B[f]-A[f])*t; }
  out.term=a; out.t=p-a; out.phase=p;
  return out;
}
const cl=v=>v<0?0:v>255?255:v|0;
export const rgb2int = c => (cl(c[0])<<16)|(cl(c[1])<<8)|cl(c[2]);
export const mix = mixRGB;
export function shade(c,k){ return [c[0]*k,c[1]*k,c[2]*k]; }
export function lift(c,k){ return [c[0]+(255-c[0])*k, c[1]+(255-c[1])*k, c[2]+(255-c[2])*k]; }
